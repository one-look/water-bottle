"""Qdrant vector retrieval service with tenant isolation and hybrid search (Dense + BM25 RRF)."""

from functools import lru_cache
from typing import Any, Dict, List, Optional
from fastembed import SparseTextEmbedding
from pydantic import BaseModel, Field, validate_call
from qdrant_client import AsyncQdrantClient
from qdrant_client.http import models as qmodels
from qdrant_client.http.exceptions import UnexpectedResponse

from src.core.logging import setup_logger

logger = setup_logger(__name__)


@lru_cache(maxsize=4)
def get_sparse_embedder(model_name: str) -> SparseTextEmbedding:
    """Cached singleton instance of FastEmbed SparseTextEmbedding to prevent repeated model downloads/checks."""
    logger.info(f"Loading FastEmbed sparse BM25 model singleton: '{model_name}'")
    return SparseTextEmbedding(model_name=model_name)

class QdrantRetrieverConfig(BaseModel):
    """Configuration schema for Qdrant retriever initialization."""

    collection_name: str = Field(..., min_length=1, description="Target collection name")
    top_k: int = Field(5, ge=1, le=100, description="Number of top document chunks to retrieve")
    score_threshold: float = Field(0.0, ge=0.0, le=1.0, description="Minimum similarity score cutoff")
    hybrid: bool = Field(True, description="Enable hybrid dense + BM25 sparse search with RRF")
    sparse_model_name: Optional[str] = Field(
        default="Qdrant/bm25",
        description="FastEmbed sparse BM25 model name, configurable via YAML",
    )
    use_parent_chunks: bool = Field(
        default=True,
        description="When enabled, returns the deduplicated parent context blocks for generation instead of child chunks",
    )

class RetrivedDocument(BaseModel):
    """Schema for a retrieved text chunk payload."""

    document_id: str 
    text: str
    score: float
    metadata: Dict[str, Any] = Field(default_factory=dict)

class QdrantRetriever:
    '''
    Service class for executing vector similarity and hybrid searches in Qdrant with tenant isolation.
    '''
    @validate_call(config=dict(arbitrary_types_allowed=True))
    def __init__(self, config: QdrantRetrieverConfig, client: Optional[Any] = None):
        '''
        Initializes the qdrant client connection and search settings.

        Args:
            config: validated QdrantRetrieverConfig object.
            client: Optional injected AsyncQdrantClient instance. If not provided,
                    resolves from the global application instance.
        '''
        logger.info(f"Initializing Qdrant client for collection '{config.collection_name}' (hybrid={config.hybrid})")
        if client is not None:
            self.client = client
        else:
            from src.api import application
            app_inst = application.get()
            if not app_inst or not hasattr(app_inst, "qdrant_client"):
                raise RuntimeError("Global Application instance or qdrant_client is not initialized.")
            self.client = app_inst.qdrant_client

        self.collection_name = config.collection_name
        self.top_k = config.top_k
        self.score_threshold = config.score_threshold
        self.hybrid = config.hybrid
        self.use_parent_chunks = config.use_parent_chunks
        self.sparse_embedder: Optional[SparseTextEmbedding] = None
        if self.hybrid and config.sparse_model_name:
            try:
                self.sparse_embedder = get_sparse_embedder(config.sparse_model_name)
            except Exception as e:
                logger.warning(f"Could not load FastEmbed BM25 model '{config.sparse_model_name}': {e}. Falling back to dense-only.")
                self.sparse_embedder = None

    async def retrieve(
        self,
        query_vector: List[float],
        tenant_id: str,
        query_text: Optional[str] = None,
    ) -> List[RetrivedDocument]:
        '''
        Queries Qdrant for matching vectors belonging strictly to the specified tenant.
        Uses Hybrid RRF fusion if enabled and query_text is available, otherwise falls back to dense vector search.

        Args:
            query_vector: Dense vector list generated by the query embedder.
            tenant_id: Active tenant identifier used for strict payload filtering.
            query_text: Raw query text used to compute sparse BM25 vectors for hybrid search.

        Returns:
            List[RetrivedDocument]: List of relevant document chunks above the score threshold.
        '''
        if not query_vector:
            logger.error("Empty query vector supplied to Qdrant retriever.")
            raise ValueError("Query vector cannot be empty.")

        clean_tenant_id = tenant_id.strip()
        if not clean_tenant_id:
            logger.error("Missing or blank tenant_id supplied for vector retrieval.")
            raise ValueError("Tenant ID is required for multi-tenant isolation.")

        logger.info(f"Executing Qdrant search for tenant '{clean_tenant_id}' (top_k={self.top_k}, hybrid={self.hybrid and bool(query_text and self.sparse_embedder)})")

        # construct payload filter for strict tenant isolation
        tenant_filter = qmodels.Filter(
            must=[
                qmodels.FieldCondition(
                    key="tenant_id",
                    match=qmodels.MatchValue(value=clean_tenant_id),
                )
            ]
        )

        try:
            if self.hybrid and query_text and self.sparse_embedder:
                sparse_embeddings = list(self.sparse_embedder.embed([query_text]))
                query_sparse = sparse_embeddings[0]
                sparse_vector = qmodels.SparseVector(
                    indices=query_sparse.indices.tolist(),
                    values=query_sparse.values.tolist(),
                )

                # Hybrid search using prefetch + RRF (Reciprocal Rank Fusion)
                results = await self.client.query_points(
                    collection_name=self.collection_name,
                    prefetch=[
                        qmodels.Prefetch(
                            query=query_vector,
                            using="dense",
                            filter=tenant_filter,
                            limit=self.top_k * 2,
                        ),
                        qmodels.Prefetch(
                            query=sparse_vector,
                            using="sparse",
                            filter=tenant_filter,
                            limit=self.top_k * 2,
                        ),
                    ],
                    query=qmodels.FusionQuery(fusion=qmodels.Fusion.RRF),
                    limit=self.top_k,
                )
            else:
                results = await self.client.query_points(
                    collection_name=self.collection_name,
                    query=query_vector,
                    using="dense",
                    query_filter=tenant_filter,
                    limit=self.top_k,
                    score_threshold=self.score_threshold if self.score_threshold > 0 else None,
                )

            retrieved_docs: List[RetrivedDocument] = []
            seen_parent_ids = set()

            for point in results.points:
                payload = point.payload or {}
                doc_id = payload.get("document_id", str(point.id))
                parent_id = payload.get("parent_id")
                parent_text = payload.get("parent_text")

                # If parent-child chunking is active and parent_text is present, use parent context
                if self.use_parent_chunks and parent_text:
                    if parent_id:
                        if parent_id in seen_parent_ids:
                            continue  # Deduplicate multiple children sharing the same parent
                        seen_parent_ids.add(parent_id)

                    retrieved_docs.append(
                        RetrivedDocument(
                            document_id=parent_id or doc_id,
                            text=parent_text,
                            score=point.score,
                            metadata={k: v for k, v in payload.items() if k not in ("text", "tenant_id", "parent_text")},
                        )
                    )
                else:
                    text = payload.get("text", "")
                    retrieved_docs.append(
                        RetrivedDocument(
                            document_id=doc_id,
                            text=text,
                            score=point.score,
                            metadata={k: v for k, v in payload.items() if k not in ("text", "tenant_id")},
                        )
                    )

            logger.info(f"Retrieved {len(retrieved_docs)} matching documents for tenant '{clean_tenant_id}'")
            return retrieved_docs

        except UnexpectedResponse as e:
            logger.error(f"Qdrant API error during search: {str(e)}", exc_info=True)
            raise RuntimeError(f"Qdrant database error: {str(e)}") from e
        
        except Exception as e:
            logger.error(f"Unexpected error during vector search: {str(e)}", exc_info=True)
            raise RuntimeError(f"Failed to retrieve context from Qdrant: {str(e)}") from e